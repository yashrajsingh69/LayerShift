"""
LayerShift - SVG Processing & Formatting Service
Manages SVG parsing, coordinate viewBox synchronization, complexity analysis, and export formatting.
"""

import re
import xml.etree.ElementTree as ET
from typing import Dict, Any, Tuple, Optional
from utils.validation import extract_svg_content, sanitize_and_validate_svg


def prepare_svg_for_layer(
    raw_svg_string: str,
    target_width: int,
    target_height: int,
    layer_name: str = "Layer"
) -> Tuple[bool, Optional[str], Optional[str], Dict[str, Any]]:
    """
    Validates, sanitizes, and normalizes the SVG coordinate system to match
    the target canvas dimensions exactly (viewBox="0 0 {target_width} {target_height}").
    """
    # Step 1: Extract SVG content from raw output
    success, extracted, err = extract_svg_content(raw_svg_string)
    if not success or not extracted:
        return False, None, err or "Failed to extract SVG content", {}

    # Step 2: Sanitize and validate XML
    val_success, sanitized, val_err, meta = sanitize_and_validate_svg(
        extracted,
        expected_width=target_width,
        expected_height=target_height
    )
    if not val_success or not sanitized:
        return False, None, val_err or "SVG validation failed", meta

    # Step 3: Parse sanitized XML to inspect and enforce viewBox alignment
    try:
        clean_xml = re.sub(r'<\?xml[^>]*\?>', '', sanitized).strip()
        root = ET.fromstring(clean_xml)

        # Enforce viewBox matching image coordinate space
        current_viewbox = root.attrib.get('viewBox')
        if not current_viewbox:
            root.attrib['viewBox'] = f"0 0 {target_width} {target_height}"

        root.attrib['width'] = str(target_width)
        root.attrib['height'] = str(target_height)

        # Count vector primitives
        path_count = 0
        shape_count = 0
        group_count = 0

        for elem in root.iter():
            tag = elem.tag.split('}')[-1].lower() if '}' in elem.tag else elem.tag.lower()
            if tag == 'path':
                path_count += 1
            elif tag in ('circle', 'rect', 'ellipse', 'polygon', 'polyline', 'line'):
                shape_count += 1
            elif tag == 'g':
                group_count += 1

        complexity_score = (path_count * 3) + (shape_count * 2) + group_count
        meta['path_count'] = path_count
        meta['shape_count'] = shape_count
        meta['group_count'] = group_count
        meta['complexity_score'] = complexity_score

        # Format final SVG string
        final_svg = ET.tostring(root, encoding='unicode')
        if 'xmlns=' not in final_svg:
            final_svg = final_svg.replace('<svg', '<svg xmlns="http://www.w3.org/2000/svg"', 1)

        return True, final_svg, None, meta

    except Exception as e:
        return False, None, f"Failed to normalize layer SVG: {str(e)}", meta


def format_export_svg(svg_content: str, layer_name: str = "LayerShift Export") -> str:
    """Formats an SVG file with header comments and clean declaration for file download."""
    header = (
        f'<?xml version="1.0" encoding="UTF-8"?>\n'
        f'<!-- Generated by LayerShift: Generate Editable Layers, Not Flat Pixels -->\n'
        f'<!-- Layer: {layer_name} -->\n'
    )
    clean_content = re.sub(r'<\?xml[^>]*\?>', '', svg_content).strip()
    return header + clean_content
